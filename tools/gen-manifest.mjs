#!/usr/bin/env node
// Animatio — manifest.json -> _manifest.scss. PLAN.md §3.5
//
// The manifest is the single hand-authored (or importer-generated) declaration.
// This turns it into a SCSS map so the effect() mixin can emit from it, while
// build-catalogue.mjs turns the SAME file into dist/catalogue.json for the docs,
// the gates and the tree-shake resolver. One declaration, four consumers.
//
// Everything is emitted as a QUOTED SCSS string: `#{$value}` interpolation
// strips the quotes at emit time, so values pass through byte-exact without Sass
// trying to evaluate `translate3d(...)` or `calc(...)` as arithmetic.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

const SOURCES = [
  ["src/effects/manifest.json", "src/effects/_manifest.scss", "$parity"],
  ["src/atoms/manifest.json", "src/atoms/_manifest.scss", "$atoms"],
];

const q = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

function frameMap(frames, indent) {
  const pad = " ".repeat(indent);
  const inner = " ".repeat(indent + 2);
  const stops = Object.entries(frames).map(([stop, decls]) => {
    const d = Object.entries(decls)
      .map(([p, v]) => `${" ".repeat(indent + 4)}${q(p)}: ${q(v)}`)
      .join(",\n");
    return `${inner}${q(stop)}: (\n${d}\n${inner})`;
  });
  return `(\n${stops.join(",\n")}\n${pad})`;
}

function entryMap(name, e) {
  const lines = [
    `    mode: ${q(e.mode || "fast")}`,
    `    module: ${q(e.module)}`,
    `    family: ${q(e.family)}`,
  ];
  if (e.raw) lines.push(`    raw: ${frameMap(e.raw, 4)}`);
  if (e.ch) lines.push(`    ch: ${frameMap(e.ch, 4)}`);
  if (e.rule) {
    const r = Object.entries(e.rule)
      .map(([p, v]) => `      ${q(p)}: ${q(v)}`)
      .join(",\n");
    lines.push(`    rule: (\n${r}\n    )`);
  }
  return `  ${q(name)}: (\n${lines.join(",\n")}\n  )`;
}

let total = 0;
for (const [inFile, outFile, varName] of SOURCES) {
  const src = join(ROOT, inFile);
  if (!existsSync(src)) {
    console.log(`  skip ${inFile} (not present yet)`);
    continue;
  }
  const manifest = JSON.parse(readFileSync(src, "utf8"));
  const entries = Object.entries(manifest).map(([n, e]) => entryMap(n, e));
  const scss = `// GENERATED by tools/gen-manifest.mjs — DO NOT EDIT.
// Source: ${inFile}   (PLAN.md §3.5)

${varName}: (
${entries.join(",\n")}
);
`;
  writeFileSync(join(ROOT, outFile), scss);
  console.log(`  ${outFile.padEnd(34)} ${String(entries.length).padStart(4)} entries`);
  total += entries.length;
}

console.log(`animatio: manifest -> scss ok (${total} entries)`);
